// Turns the repo's own pictures into the responsive AVIF and WebP files the landing page serves.
// A static export has no image optimiser, so the sizes are made here once and committed:
//   pnpm --filter @yuvomeet/landing images
// It also writes src/content/images.generated.ts, which the <Picture> component reads.
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '..');
const repo = path.resolve(app, '../..');
const out = path.join(app, 'public', 'img');
const seed = (f) => path.join(repo, 'supabase', 'seed', 'media', f);
const mobile = (f) => path.join(repo, 'apps', 'mobile', 'assets', f);

/** name -> source and the widths the layout asks for (1x and 2x of the largest slot). */
const PICTURES = {
  // The glow is pure blur: a tiny file scaled up looks the same, costs about 1 KB, and is low-information
  // enough that Chrome does not pick it as the LCP element (the headline is).
  glow: { src: mobile('hero.jpg'), widths: [48] },
  chai: { src: seed('venue_chai.jpg'), widths: [360, 640, 960] },
  river: { src: seed('venue_river.jpg'), widths: [360, 640, 960, 1280] },
  music: { src: seed('cover_music.jpg'), widths: [360, 640, 960] },
  sports: { src: seed('cover_sports.jpg'), widths: [360, 640, 960] },
};

await mkdir(out, { recursive: true });
const manifest = {};

for (const [name, { src, widths }] of Object.entries(PICTURES)) {
  const meta = await sharp(src).metadata();
  const sizes = widths.filter((w) => w <= (meta.width ?? 0));
  for (const w of sizes) {
    const base = sharp(src).resize({ width: w, withoutEnlargement: true });
    await base.clone().avif({ quality: 52, effort: 6 }).toFile(path.join(out, `${name}-${w}.avif`));
    await base.clone().webp({ quality: 72, effort: 6 }).toFile(path.join(out, `${name}-${w}.webp`));
  }
  manifest[name] = { width: meta.width, height: meta.height, widths: sizes };
  console.log(`${name}: ${meta.width}x${meta.height} -> ${sizes.join(', ')}`);
}

// The Hengout mark, from the app icon (apps/mobile/assets/icon.png): a black canvas holding a rounded
// square. Crop to the square and round its corners, so the mark sits on any background.
const icon = mobile('icon.png');
const { width: iw } = await sharp(icon).metadata();
const inset = Math.round(iw * 0.086); // the square starts 8.6% in from each edge
const side = iw - 2 * inset;
async function mark(size) {
  const radius = Math.round(size * 0.225);
  const mask = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="#fff"/></svg>`);
  return sharp(icon)
    .extract({ left: inset, top: inset, width: side, height: side })
    .resize(size, size)
    .composite([{ input: mask, blend: 'dest-in' }])
    .png({ compressionLevel: 9 })
    .toBuffer();
}
for (const s of [96, 192, 256, 512]) await writeFile(path.join(out, `mark-${s}.png`), await mark(s));
await writeFile(path.join(app, 'src', 'app', 'apple-icon.png'), await mark(180));
await writeFile(path.join(app, 'src', 'app', 'icon.png'), await mark(64));
console.log('marks: 96, 192, 256, 512, apple-icon.png, icon.png');

const ts = `// Generated by scripts/images.mjs. Do not edit by hand.\nexport const IMAGES = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type ImageName = keyof typeof IMAGES;\n`;
await mkdir(path.join(app, 'src', 'content'), { recursive: true });
await writeFile(path.join(app, 'src', 'content', 'images.generated.ts'), ts);
